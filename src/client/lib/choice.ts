/** 選択肢の**表示**だけを整える。
 *
 *  組合せを問う問題の選択肢は、原本では小さな表として組まれている。
 *  書き起こしでは1行に潰れるため、「a：（2 の i 乗）－ 1，b：…」や
 *  「品名：ガム，価格：100 ／ 品名：せんべい，価格：250 ／ …」のような
 *  読みづらい1行になる。項目の切れ目で改行して縦に並べると、
 *  選択肢どうしの違いが同じ位置に来て見比べられる。
 *
 *  データは触らない。ここで返した行を画面が並べるだけ。
 *
 *  **やり過ぎないこと。** 読点「，」を含むだけの普通の文
 *  （「信頼性を高めるため，このディスクを二重化した。」）は1行のまま出す。
 *  区切りに見えるものが本当に「項目名：値」の並びであるときだけ割る。 */

/** 「，」の直後に「短い項目名＋：」が続く位置。ここが項目の切れ目。
 *  項目名を14文字までに限るのは、文の途中の読点を拾わないため。 */
const KEY_BREAK = /，(?=[^，／：]{1,14}：)/

/** これより短い選択肢は、1行でも十分読める。 */
const MIN_LEN = 30

// @implements REQ-044
export function formatChoice(v: string): string[] {
  // 「／」は書き起こしで項目グループの区切りに使っている。
  // 「：」も含むときだけ組合せと見なす（分数や単位の「／」を割らない）。
  if (v.includes('／') && v.includes('：')) {
    const lines = v
      .split('／')
      .map((s) => s.trim())
      .filter((s) => s)
    if (lines.length >= 2) return lines
  }

  if (v.length > MIN_LEN && KEY_BREAK.test(v)) {
    const lines = v
      .split(KEY_BREAK)
      .map((s) => s.trim())
      .filter((s) => s)
    // 全ての行が「項目名：値」になったときだけ割る。1つでも「：」を持たない行が
    // できるなら、それは項目の並びではなく普通の文の読点を割っている
    // （「…の比が，n を大きくすると π：1 に近づく…」のような文が実在する）。
    if (lines.length >= 2 && lines.every((s) => s.includes('：'))) return lines
  }

  return [v]
}
